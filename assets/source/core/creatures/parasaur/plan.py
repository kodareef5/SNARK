def interpolate(rows, subdivisions=4):
    """Shape-preserving cubic Hermite over strictly increasing stations."""
    a=np.array(rows,dtype=float)
    x=a[:,0]; y=a[:,1:]; h=np.diff(x); delta=np.diff(y,axis=0)/h[:,None]
    m=np.zeros_like(y); m[0]=delta[0];m[-1]=delta[-1]
    for i in range(1,len(a)-1):
        pos=delta[i]*delta[i-1]>0
        w1=2*h[i]+h[i-1];w2=h[i]+2*h[i-1]
        m[i,pos]=(w1+w2)/(w1/delta[i-1,pos]+w2/delta[i,pos])
    out=[]
    for i in range(len(h)):
        for t in np.arange(subdivisions)/subdivisions:
            v=(2*t**3-3*t*t+1)*y[i]+(-2*t**3+3*t*t)*y[i+1]
            v+=(t**3-2*t*t+t)*h[i]*m[i]+(t**3-t*t)*h[i]*m[i+1]
            out.append([x[i]+t*h[i],*v])
    return np.array(out+[list(a[-1])])
