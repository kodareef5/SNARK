#!/usr/bin/env python3
"""Paint all four wing pieces. Run from any directory; no Blender or network.

Membrane, skin and accepted fuzz study layers are read on every run. Missing
fuzz deliveries are regenerated by the study's own unmodified build.py; other
missing study outputs rebuild in a private copy inside checks/.
All vascular geometry and colour boundaries are evaluated in animal space.
"""
from pathlib import Path
import hashlib
import json
import os
import shutil
import subprocess
import sys

import numpy as np
from PIL import Image
from scipy.ndimage import gaussian_filter, gaussian_filter1d, map_coordinates
from scipy.interpolate import CubicSpline
from scipy.spatial import cKDTree

HERE = Path(__file__).resolve().parent
PAINT = HERE.parent
ASSET = PAINT.parent.parent
STUDIES = ASSET / 'tex/studies'
BAKES = ASSET / 'ref/bakes'
MATERIAL = 'pteranodon_wing'
CHECKS = HERE / 'checks'
LAYERS = HERE / 'layers'
RECIPE = json.loads((HERE / 'source/recipe.json').read_text())
SOURCES = {}


def linear(s):
    s = np.asarray(s, np.float32)
    return np.where(s <= .04045, s / 12.92, ((s + .055) / 1.055) ** 2.4)


def srgb(l):
    l = np.clip(l, 0, 1)
    return np.where(l <= .0031308, l * 12.92, 1.055 * l ** (1 / 2.4) - .055)


def smooth(a, b, x):
    t = np.clip((x - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)


def read(path):
    SOURCES[str(path.relative_to(ASSET))] = hashlib.sha256(path.read_bytes()).hexdigest()
    return np.asarray(Image.open(path))


def study(name, required):
    origin = STUDIES / name
    if all((origin / p).exists() for p in required):
        return origin
    # The brief explicitly permits rebuilding missing study deliveries. Isolate
    # its output so that another painter's files are never edited by this build.
    target = CHECKS / 'study_cache' / name
    target.mkdir(parents=True, exist_ok=True)
    for p in origin.glob('*.py'):
        shutil.copy2(p, target / p.name)
    for p in origin.glob('*.json'):
        shutil.copy2(p, target / p.name)
    (target / 'source').mkdir(exist_ok=True)
    for p in (origin / 'source').iterdir():
        if p.is_file():
            shutil.copy2(p, target / 'source' / p.name)
    subprocess.run([sys.executable, str(target / 'build.py')], check=True,
                   env={**os.environ, 'PYTHONDONTWRITEBYTECODE': '1'})
    return target


def fuzz_study():
    """Read the live accepted deliveries; rebuild them only when missing."""
    origin = STUDIES / 'fuzz'
    required = ['study.json'] + [f'{name}_{layer}.png'
        for name in ['fuzz', 'fuzz_face'] for layer in ['base', 'height', 'packed']]
    if not all((origin / p).is_file() for p in required):
        subprocess.run([sys.executable, str(origin / 'build.py')], check=True,
                       cwd=origin, env={**os.environ, 'PYTHONDONTWRITEBYTECODE': '1'})
    return origin


def sample(field, u, v, span=1., blur=0.):
    """Periodic physical sampling, filtered before reduction to avoid aliasing."""
    if blur:
        field = gaussian_filter(field, blur, mode='wrap')
    n = field.shape[0]
    return map_coordinates(field, [(v / span * n) % n, (u / span * n) % n],
                           order=1, mode='grid-wrap', prefilter=False)


def study_layers(folder, name, u, v, span, texel, relief_scale=1.):
    info = json.loads((folder / 'study.json').read_text())['sets'][name]
    blur = max(.5, float(np.median(texel)) * 2048 / (span * 1000) * .40)
    b = linear(read(folder / f'{name}_base.png')[..., 0] / 255.)
    h = read(folder / f'{name}_height.png').astype(np.float32) / 65535 * info['height_mm']
    p = read(folder / f'{name}_packed.png').astype(np.float32) / 255
    return (sample(b, u, v, span, blur),
            sample(h - np.mean(h), u, v, span, blur) * relief_scale,
            sample(p[..., 1], u, v, span, blur),
            sample(p[..., 0], u, v, span, blur))


def curves_from_study(folder):
    """Retain the traced source's bends and taper as small vascular templates.

    Placement, roots and branch connectivity are specific to this wing. Source
    curves supply smooth deviations from each path's chord, not a repeated tile.
    """
    path = folder / 'source/paths.json'
    SOURCES[str(path.relative_to(ASSET))] = hashlib.sha256(path.read_bytes()).hexdigest()
    traced = json.loads(path.read_text())['paths']
    templates = []
    for p in traced:
        q = np.asarray(p['points'], np.float32)
        if len(q) < 10:
            continue
        delta = q[-1] - q[0]
        length = float(np.linalg.norm(delta))
        if length < .025:
            continue
        arc = np.r_[0, np.cumsum(np.linalg.norm(np.diff(q, axis=0), axis=1))]
        t = arc / arc[-1]
        normal = np.array([-delta[1], delta[0]]) / length
        bend = (q - q[0] - t[:, None] * delta) @ normal
        templates.append((t, bend / max(length, .05), float(np.mean(p['strengths']))))
    return templates


class Wing:
    def __init__(self):
        self.meta = json.loads((PAINT / f'{MATERIAL}_pieces.json').read_text())
        self.piece = read(PAINT / f'{MATERIAL}_pieces.png')[..., 0]
        self.number = {p['name']: p['number'] for p in self.meta['pieces']}
        self.cover = np.isin(self.piece, list(self.number.values()))
        xyz = []
        for k, axis in enumerate('xyz'):
            q = read(PAINT / f'{MATERIAL}_position_{axis}.png').astype(np.float32) / 65535
            low, high = self.meta['position_box']['min'][k], self.meta['position_box']['max'][k]
            xyz.append(low + q * (high - low))
        self.x, self.y, self.z = abs(xyz[0]), xyz[1], xyz[2]
        self.mm = read(PAINT / f'{MATERIAL}_texel_mm.png').astype(np.float32) / 1000
        self.normal = read(BAKES / f'{MATERIAL}_normal_object.png').astype(np.float32) / 127.5 - 1
        self.flow = read(BAKES / f'{MATERIAL}_flow.png').astype(np.float32) / 127.5 - 1
        self.shape = self.piece.shape
        self.mem = self.mask('membrane_upper') | self.mask('membrane_under')
        under = self.mask('membrane_under')
        ys, xs = np.where(under)
        # X/Z coordinates of the under band form a near-isometric plan view.
        idx = np.arange(0, len(xs), 12)
        self.ftree = cKDTree(np.c_[self.x[ys[idx], xs[idx]], self.z[ys[idx], xs[idx]]])
        self.fval = np.c_[self.flow[ys[idx], xs[idx], 0], self.flow[ys[idx], xs[idx], 1]]
        # Derive trailing and flank boundaries afresh from this bake, not UV boxes.
        self.bx = np.linspace(self.x[under].min(), self.x[under].max(), 1600)
        bins = np.clip(np.searchsorted(self.bx, self.x[under]), 0, len(self.bx) - 1)
        trail = np.full(len(self.bx), np.inf)
        np.minimum.at(trail, bins, self.z[under])
        good = np.isfinite(trail)
        self.trail = gaussian_filter1d(np.interp(self.bx, self.bx[good], trail[good]), 2)
        self.bz = np.linspace(self.z[under].min(), .13, 700)
        bins = np.clip(np.searchsorted(self.bz, self.z[under]), 0, len(self.bz) - 1)
        flank = np.full(len(self.bz), np.inf)
        np.minimum.at(flank, bins, self.x[under])
        good = np.isfinite(flank)
        self.flank = gaussian_filter1d(np.interp(self.bz, self.bz[good], flank[good]), 3)
        # Arm/finger centreline: derive it from the average of each round strip.
        spar = self.mask('arm') | self.mask('finger')
        self.cx = np.linspace(self.x[spar].min(), self.x[spar].max(), 700)
        bins = np.clip(np.searchsorted(self.cx, self.x[spar]), 0, len(self.cx) - 1)
        count = np.bincount(bins, minlength=len(self.cx))
        good = count > 0
        self.cy, self.cz = [gaussian_filter1d(np.interp(self.cx, self.cx[good],
            (np.bincount(bins, weights=v[spar], minlength=len(self.cx)) / np.maximum(count, 1))[good]), 2)
            for v in [self.y, self.z]]

    def mask(self, name):
        return self.piece == self.number[name]

    def lead(self, x):
        return np.interp(x, self.cx, self.cz)

    def trailing(self, x):
        return np.interp(x, self.bx, self.trail)

    def root(self, z):
        return np.interp(z, self.bz, self.flank)

    def direction(self, p):
        _, i = self.ftree.query(p)
        d = self.fval[i].copy()
        d[0] = max(.08, d[0])
        d[1] = min(-.25, d[1])
        return d / np.linalg.norm(d)

    def inside(self, p, margin=.003):
        x, z = p
        return (self.bx[0] <= x <= self.bx[-1] and
                z >= self.trailing(x) + margin and x >= self.root(z) + margin and
                z <= self.lead(x) + .008)


def vascular_paths(w, folder):
    """A sparse authored graph, then unequal fine growth from its connected limbs.

    The four supply routes and their early/late forks are individual animal-space
    paths. There is no sequence of roots or fork fractions along the span.
    """
    rng = np.random.default_rng(RECIPE['seed'])
    templates = curves_from_study(folder)
    source = HERE / 'source/network.json'
    SOURCES[str(source.relative_to(ASSET))] = hashlib.sha256(source.read_bytes()).hexdigest()
    specs = json.loads(source.read_text())['paths']
    paths, named = [], {}

    def location(path, fraction):
        q = path['points']
        arc = np.r_[0, np.cumsum(np.linalg.norm(np.diff(q, axis=0), axis=1))]
        k = np.clip(np.searchsorted(arc, arc[-1]*fraction), 1, len(q)-2)
        direction = q[k+1]-q[k-1]
        return q[k].copy(), direction/np.linalg.norm(direction), float(arc[k]/arc[-1])

    def add(points, width, end, strength, kind, fade=True, **metadata):
        paths.append(dict(points=np.asarray(points, np.float32), width=width, end=end,
                          strength=strength, kind=kind, fade=fade, **metadata))
        return len(paths)-1

    for spec in specs:
        parent = spec.get('parent')
        if parent:
            start, tangent, fraction = location(paths[named[parent]], spec['at'])
        elif spec['root'][0] == 'spar':
            x = spec['root'][1]
            start = np.array([x, w.lead(x)+.003])
            tangent = w.direction(start)
        else:
            z = spec['root'][1]
            start = np.array([w.root(z)-.003, z])
            tangent = np.array([.83,-.56])
        controls = [start, *spec['guides']]
        join = spec.get('join')
        if join:
            finish, _, _ = location(paths[named[join[0]]], join[1])
            controls.append(finish)
        controls = np.asarray(controls)
        arc = np.r_[0,np.cumsum(np.linalg.norm(np.diff(controls,axis=0),axis=1))]
        spline = CubicSpline(arc, controls, bc_type=((1,tangent),'natural'))
        points = spline(np.linspace(0,arc[-1],max(24,int(arc[-1]/.0015))))
        # Retain small departures from a perfect spline from the study's actual
        # drawn centrelines. Zero at attachments keeps the graph connected.
        t = np.linspace(0,1,len(points))
        template = templates[sum(spec['id'].encode()) % len(templates)]
        offset = np.interp(t,template[0],template[1])*min(.12,arc[-1]*.20)
        tangent_field = np.gradient(points,axis=0)
        normal = np.c_[-tangent_field[:,1],tangent_field[:,0]]
        normal /= np.linalg.norm(normal,axis=1)[:,None]
        # Millimetre-scale unequal bends break the mechanically smooth guide;
        # their envelope vanishes at both attachment points.
        bend_rng = np.random.default_rng(RECIPE['seed']+sum(spec['id'].encode())*997)
        knots = np.r_[0,np.cumsum(bend_rng.uniform(.018,.047,max(8,int(arc[-1]/.018))))]
        knots /= knots[-1]
        small = np.interp(t,knots,bend_rng.normal(0,.0018,len(knots)))
        small = gaussian_filter1d(small,3)
        points += normal*((offset+small)*np.sin(np.pi*t)**2)[:,None]
        # Keep terminal cap clear of the actual trailing edge after a rebake.
        for k in range(8,len(points)):
            if not w.inside(points[k],.006):
                points = points[:k]
                join = None
                break
        kind = 'trunk' if not parent else ('connection' if join else 'branch')
        index = add(points,spec['width'],spec['end'],1.0 if not parent else .83,
                    kind,fade=not join,id=spec['id'],parent=parent,join=join)
        named[spec['id']] = index

    # Secondary growth uses unrelated spacings, lengths, sides and branch counts.
    # A close encounter reconnects at the existing centreline, rather than making
    # a cross or stopping all branches at the same arbitrary clearance.
    generation = list(range(len(paths)))
    for depth in range(2):
        following = []
        for index in generation:
            parent = paths[index]
            if parent['kind'] == 'connection':
                continue
            pts = parent['points']
            length = float(np.linalg.norm(np.diff(pts,axis=0),axis=1).sum())
            if length < .055:
                continue
            if depth == 0:
                count = int(rng.integers(2,7)) if length > .23 else int(rng.integers(0,4))
            else:
                count = int(rng.integers(0,4))
            fractions = sorted(rng.uniform(.12,.88,count))
            accepted = []
            for j,f in enumerate(fractions):
                if any(abs(f-a)*length < .038 for a in accepted):
                    continue
                accepted.append(f)
                start,direction,f = location(parent,f)
                side = rng.choice([-1,1])
                normal = np.array([-direction[1],direction[0]])*side
                reach = rng.uniform(.065,.205) if depth == 0 else rng.uniform(.028,.095)
                reach *= rng.uniform(.65,1.15)
                t = np.linspace(0,1,max(20,int(reach/.0015)))
                template = templates[int(rng.integers(len(templates)))]
                bend = np.interp(t,template[0],template[1])*reach*.38
                opening = rng.uniform(.28,.78)
                curve = start+(t*reach)[:,None]*direction + (reach*opening*t**1.5+bend)[:,None]*normal
                others = np.concatenate([p['points'] for n,p in enumerate(paths) if n != index])
                distances, nearest = cKDTree(others).query(curve)
                joined = False
                for k in range(5,len(curve)):
                    if not w.inside(curve[k],.009):
                        curve = curve[:k]
                        break
                    if np.linalg.norm(curve[k]-start)>.025 and distances[k]<.003:
                        curve = curve[:k+1]
                        curve[-1] = others[nearest[k]]
                        joined = True
                        break
                if len(curve)<12 or np.linalg.norm(curve[-1]-start)<.024:
                    continue
                width = min(1.9, (parent['width']*(1-f)+parent['end']*f)*rng.uniform(.52,.66))
                width = max(1.55,width)
                child = add(curve,width,.80 if depth else 1.0,
                            rng.uniform(.62,.80) if depth == 0 else rng.uniform(.43,.62),
                            'twig',fade=not joined,parent=index,joined=joined)
                following.append(child)
        generation = following

    # Small front-membrane vessels remain independent of the main rearward sheet;
    # unequal extents and forks avoid reproducing the former seven little trees.
    for i,(x,extent,forks) in enumerate([(.27,.046,[.21]),(.48,.084,[.39,.76]),(.81,.037,[])]):
        t = np.linspace(0,1,40)
        curve = np.c_[x+.035*t+.009*np.sin(t*2.7),w.lead(x)+extent*t]
        add(curve,2.3-i*.22,.85,.65,'front')
        for j,f in enumerate(forks):
            start = curve[round(f*39)]
            q = np.linspace(0,1,20)
            side = -1 if (i+j)%2 else 1
            add(start+np.c_[side*(.019+.013*i)*q**1.3,.025*q],1.45,.65,.44,'front')
    return paths


def wash_support(w):
    """The approved wash edge is independent of this round's new vessels."""
    source = HERE / 'source/wash_support.json'
    SOURCES[str(source.relative_to(ASSET))] = hashlib.sha256(source.read_bytes()).hexdigest()
    paths = json.loads(source.read_text())['paths']
    for p in paths:
        p['points'] = np.asarray(p['points'],np.float32)
    return raster_paths(paths,w,diagnostics=False,hold_trunk_width=False)


def raster_paths(paths, w, diagnostics=True, hold_trunk_width=True):
    ppm = 1200
    xmin, zmax = 0., .15
    canvas = np.zeros((int((zmax + 1.12) * ppm) + 1, int(3.53 * ppm) + 1), np.float32)
    for path in paths:
        pts = path['points']
        arc = np.r_[0, np.cumsum(np.linalg.norm(np.diff(pts, axis=0), axis=1))]
        t = arc / max(arc[-1], 1e-6)
        taper = smooth(.38,1.,t) if hold_trunk_width and path['kind'] == 'trunk' else t
        widths = path['width'] * (1 - taper) + path['end'] * taper
        strength = path['strength'] * (1 - .22 * t)
        if path['fade']:
            strength *= smooth(0, min(.024, arc[-1] * .35), arc[-1] - arc)
        px = np.c_[(pts[:, 0] - xmin) * ppm, (zmax - pts[:, 1]) * ppm]
        for k in range(len(px) - 1):
            a, b = px[k:k + 2]
            sigma = max(.36, (widths[k] + widths[k+1]) * .5 * ppm / 2355)
            radius = sigma * 3 + 1
            x0, y0 = np.maximum(0, np.floor(np.minimum(a, b) - radius).astype(int))
            x1, y1 = np.minimum([canvas.shape[1]-1, canvas.shape[0]-1], np.ceil(np.maximum(a,b) + radius).astype(int))
            if x1 < x0 or y1 < y0:
                continue
            yy, xx = np.mgrid[y0:y1+1, x0:x1+1]
            delta = b - a
            u = np.clip(((xx-a[0])*delta[0]+(yy-a[1])*delta[1]) / max(np.dot(delta,delta),1e-9),0,1)
            d2 = (xx-a[0]-u*delta[0])**2 + (yy-a[1]-u*delta[1])**2
            v = np.exp(-d2/(2*sigma*sigma)) * (strength[k]*(1-u)+strength[k+1]*u)
            patch = canvas[y0:y1+1,x0:x1+1]
            np.maximum(patch, v, out=patch)
    coords = [(zmax - w.z[w.mem]) * ppm, (w.x[w.mem] - xmin) * ppm]
    value = map_coordinates(canvas, coords, order=1, mode='constant', prefilter=False)
    if diagnostics:
        Image.fromarray(np.rint(np.clip(canvas,0,1)*255).astype(np.uint8)).resize((1765,635)).save(CHECKS/'vascular_plan.png')
        (CHECKS/'vessels.json').write_text(json.dumps([dict(p,points=np.round(p['points'],6).tolist()) for p in paths],indent=1)+'\n')
    return value


def membrane(w, folder):
    m = w.mem
    x, z = w.x[m], w.z[m]
    # Nonuniform physical warp breaks the source's metre repetition, while both
    # faces sample precisely the same material at each X/Z point.
    u = x + .027 * np.sin(4.3 * x - 2.7*z) + .012 * np.sin(10.9*z + 1.3*x)
    v = -z + .019 * np.sin(5.7*x + 3.1*z)
    fields = []
    for name in ['skin_detail','skin_thickness','skin_gathered_detail','skin_stretch_detail','pleats']:
        a = read(folder / 'source' / f'{name}.png').astype(np.float32) / 65535
        if name != 'pleats':
            a = (a - .5) * 10
        # ~600 px/m; filter the finer source before sampling.
        fields.append(sample(a,u,v,blur=1.05))
    micro, thick, middle, stretch, pleat = fields
    veins = raster_paths(vascular_paths(w, folder), w)
    lead = w.lead(x)
    from_lead = abs(z - lead)
    from_root = np.maximum(0,x-w.root(z))
    lead_gather = np.exp(-from_lead/.075)
    root_gather = np.exp(-from_root/.095)
    gather = np.maximum(lead_gather,root_gather)
    gather *= .70 + .30*smooth(.0,.30,1-abs(np.sin(3*x+z)))
    trailing = np.maximum(0,z-w.trailing(x))
    edge = np.exp(-trailing/.0055) * (z < lead-.025)
    quiet = 1 - .55 * edge
    under = w.piece[m] == w.number['membrane_under']
    target = np.where(under,.60,.40)
    # Bring the upper/under pigment to the same neutral value exactly at the
    # insertion. This is a material transition, never a form-light gradient.
    meeting = np.exp(-(from_lead/.011)**2)
    target = target*(1-meeting)+.5*meeting
    pleat_field = read(folder / 'source/pleats.png').astype(np.float32) / 65535
    pleat_lead = sample(pleat_field, u, .22 + from_lead*2.7, blur=1.1)
    pleat_root = sample(pleat_field, -z, .24 + from_root*2.4, blur=1.1)
    pleat = (pleat_lead*lead_gather + pleat_root*root_gather) / np.maximum(.001,lead_gather+root_gather)
    fine = np.maximum(-micro,0)
    medium = np.maximum(-middle,0)
    stretched = np.maximum(-stretch,0)
    b = target + target*.014*thick - np.where(under,.265,.130)*veins
    b -= quiet*(np.where(under,.072,.045)*medium + .039*stretched + .030*fine)
    b -= gather*(.030*medium+.065*pleat) + .014*edge
    h = .4 - quiet*(.012*fine+.010*medium+.008*stretched)
    h += RECIPE['vein_rise_mm']*veins + .006*thick
    h -= gather*(.015*medium+RECIPE['gathered_pleat_depth_mm']*pleat)
    rough = .755 + .010*micro - .035*veins - .020*edge + .012*gather
    ao = 1 - np.clip(.014*fine+.010*medium+.035*gather*pleat,0,.065)
    # Hide a small, even crease where skin enters the back of the spar.
    h -= .025 * np.exp(-((from_lead-.009)/.004)**2)
    # Hold each actual face mean after all its drawing is in place.
    for is_under,mean in [(False,.4),(True,.6)]:
        sel = under == is_under
        b[sel] += mean-b[sel].mean()
    return b,h,rough,ao,veins,gather


def limb(w, name, fuzz, skin):
    m = w.mask(name)
    x,y,z = w.x[m],w.y[m],w.z[m]
    # The authored strips are isometric along their length and around the bone.
    # Integrate each column's measured mm/texel; using an angle projection here
    # pinches the fibre field into bands on the cylinder's front and back.
    rows, cols = np.where(m)
    ncols = w.shape[1]
    count = np.bincount(cols, minlength=ncols)
    valid = count > 0
    column_mm = np.bincount(cols, weights=w.mm[m], minlength=ncols) / np.maximum(count,1)
    column_mm = np.interp(np.arange(ncols),np.flatnonzero(valid),column_mm[valid])
    along_columns = np.cumsum(column_mm)/1000
    along_columns -= along_columns[np.flatnonzero(valid)[0]]
    lo = np.full(ncols,9999.);hi = np.full(ncols,-9999.)
    np.minimum.at(lo,cols,rows);np.maximum.at(hi,cols,rows)
    mid = (lo[cols]+hi[cols])/2
    cross = (rows-mid)*column_mm[cols]/1000
    along = along_columns[cols]
    # A small aperiodic drift changes the tile's phase without changing fibre scale.
    cross += .008*np.sin(along*5.3)+.004*np.sin(along*11.7)
    # At the cut behind the bone the skin inserts into the membrane. Both ends
    # of the strip converge to identical, quiet value and physical relief.
    edge_distance = np.minimum(rows-lo[cols],hi[cols]-rows)*column_mm[cols]/1000
    seam = 1-smooth(.001,.010,edge_distance)
    insertion = 1-smooth(.003,.020,edge_distance)
    fb,fh,fr,fo = study_layers(fuzz,'fuzz',cross,along,.5,w.mm[m])
    # Short 3–6 mm fuzz only at the finger's knuckle, read live from its study.
    if name == 'finger':
        fb,fh,fr,fo = study_layers(fuzz,'fuzz_face',cross,along,.25,w.mm[m])
    sb,sh,sr,so = study_layers(skin,'skin',cross,along,.14,w.mm[m],.55)
    sb = .5+(sb-.5)*.62
    # Small anisotropic wrinkles from the membrane's skin are added below by
    # the skin tile itself; no geometric ribbing or drawn light round the bone.
    if name == 'arm':
        coverage = 1-.80*smooth(1.23,1.55,x)
    else:
        coverage = .22*(1-smooth(1.51,1.86,x))
    # Fuzz calms at the membrane insertion and at the shoulder's shared boundary.
    coverage *= 1-.70*insertion
    b = sb*(1-coverage)+fb*coverage
    h = .4+sh*(1-coverage)+fh*coverage
    rough = (.76+(sr-.7)*.25)*(1-coverage)+fr*coverage
    ao = so*(1-coverage)+fo*coverage
    h -= .022*insertion
    b = b*(1-seam)+.5*seam
    h = h*(1-seam)+.378*seam
    rough = rough*(1-seam)+.76*seam
    ao = ao*(1-seam)+.995*seam
    b += .5-b.mean()
    return b,h,rough,ao


def region_masks(w, veins):
    masks = np.zeros(w.shape+(6,),np.float32)
    x,z = w.x,w.z
    tip_x = RECIPE['tip_fraction']*float(w.bx[-1])
    # The same anatomical plane cuts the membrane and the round finger.
    tip = smooth(tip_x-RECIPE['tip_blend_m']/2,tip_x+RECIPE['tip_blend_m']/2,
                 x + .006*np.sin(7*z+2.1))
    m = w.mem
    distance = x[m]-w.root(z[m])
    # A quiet, irregular wash edge bent toward the tip, with the very same veins
    # adding tiny warm tongues. It is never a straight UV-column boundary.
    wave = .018*np.sin(13*z[m]+2*x[m])+.010*np.sin(26*z[m]-3*x[m])
    distance -= wave+.018*veins
    wash = 1-smooth(.025,RECIPE['wash_fade_m'],distance)
    # Front membrane away from the flank remains region 4, per the paint brief.
    masks[...,0][m] = tip[m]
    masks[...,1][m] = (1-tip[m])*wash
    masks[...,4][m] = (1-tip[m])*(1-wash)
    arm,finger = w.mask('arm'),w.mask('finger')
    masks[...,5][arm] = 1
    masks[...,0][finger] = tip[finger]
    masks[...,5][finger] = 1-tip[finger]
    # Quantise with an exact 255-sum, including all blend pixels.
    values = masks[w.cover]*255
    floor = np.floor(values).astype(np.uint8)
    remainder = 255-floor.astype(np.int32).sum(1)
    priority = np.argsort(-(values-floor),axis=1,kind='stable')
    for n in range(6):
        selected = np.flatnonzero(remainder>n)
        floor[selected,priority[selected,n]] += 1
    result = np.zeros(w.shape+(6,),np.uint8)
    result[w.cover] = floor
    return result


def encode_base(b, w, weights):
    # A low-amplitude partition-of-unity correction holds region means without
    # erasing the required difference between the membrane's two faces.
    wr = weights[w.cover].astype(np.float32)/255
    active = [0,1,4,5]
    columns = wr[:,active]
    values = b[w.cover]
    # Four scalar reductions avoid platform-dependent BLAS accumulation and
    # spurious floating-point warnings from Accelerate's skinny matrix kernels.
    sums = np.array([c.sum(dtype=np.float64) for c in columns.T])
    gram = np.array([[(a*b).sum(dtype=np.float64) for b in columns.T] for a in columns.T])
    for _ in range(3):
        err = .5*sums-np.array([(c*values).sum(dtype=np.float64) for c in columns.T])
        delta = np.linalg.solve(gram,err)
        for c,d in zip(columns.T,delta):
            values += c*float(d)
    b[w.cover] = values
    result = np.zeros(w.shape+(4,),np.uint8)
    q = np.rint(srgb(b[w.cover])*255).astype(np.uint8)
    result[w.cover,:3] = q[:,None]
    result[w.cover,3] = 255
    return result


