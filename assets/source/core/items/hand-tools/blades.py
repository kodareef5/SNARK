"""Pike and sword silhouettes around the palm in engine metres."""

from mathutils import Vector

from hand_geometry import Y, Z


def keep_rows(level, rows, reduced):
    return rows if level == 0 else [rows[index] for index in reduced[level - 1]]


def blade_shell(prop, profile, upper):
    section = [*upper, *((x, -y) for x, y in reversed(upper) if y)]
    rings = [[Vector((x * width, y * height, z)) for x, y in section]
             for z, width, height in profile]
    prop.shell(rings, "steel")


