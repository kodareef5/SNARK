def sling_strip(prop, path, sections, sides, thickness, surface):
    points = [Vector(point[:3]) for point in path]
    rings = []
    for index in sections:
        center = points[index]
        tangent = (points[min(index + 1, len(points) - 1)] - points[max(index - 1, 0)]).normalized()
        across = (Y - tangent * Y.dot(tangent)).normalized()
        up = tangent.cross(across)
        ring = []
        for side in range(sides):
            angle = tau * (side + 0.5) / sides
            ring.append(center + cos(angle) * thickness * across + sin(angle) * path[index][3] * up)
        rings.append(ring)
    prop.shell(rings, surface, smooth=True)


