"""Original early-game hand props in engine axes, with the palm at the origin."""

from math import cos, sin, tau

from mathutils import Vector

from hand_geometry import X, Y, Z


def rounded_body(prop, stations, sides, *, phase, cap_surface=None):
    rings = []
    for z, bend, lift, width, depth, uneven, _ in stations:
        center = bend * X + lift * Y + z * Z
        ring = []
        for side in range(sides):
            angle = phase + side * tau / sides
            radius = 1 + uneven * sin(3 * angle + z * 11)
            ring.append(center + radius * (width * cos(angle) * X + depth * sin(angle) * Y))
        rings.append(ring)
    prop.shell(rings, stations[0][-1], smooth=True, cap_surface=cap_surface,
               band_surfaces=[station[-1] for station in stations[:-1]])


