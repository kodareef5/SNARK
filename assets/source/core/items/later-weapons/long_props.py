"""Build three palm-centred long props with authored distance silhouettes."""

from math import cos, pi, sin

from hand_geometry import Y, Z


def body(prop, surface, rows):
    rings = []
    for z, w, bottom, top, last_level in rows:
        if prop.level > last_level:
            continue
        cut = min(w * 0.55, (top - bottom) * 0.24)
        if prop.level == 0:
            corners = ((w - cut, bottom + cut), (w - cut, top - cut),
                       (-w + cut, top - cut), (-w + cut, bottom + cut))
            section = []
            for quarter, (x, y) in enumerate(corners):
                for segment in range(4):
                    angle = (quarter * 3 + segment - 3) * pi / 6
                    section.append((x + cut * cos(angle), y + cut * sin(angle), z))
        elif prop.level == 1:
            section = [(-w + cut, bottom, z), (w - cut, bottom, z), (w, bottom + cut, z), (w, top - cut, z),
                       (w - cut, top, z), (-w + cut, top, z), (-w, top - cut, z), (-w, bottom + cut, z)]
        elif prop.level == 2:
            section = [(-w + cut, bottom, z), (w - cut, bottom, z), (w, bottom + cut, z),
                       (w, top, z), (-w, top, z), (-w, bottom + cut, z)]
        else:
            section = [(-w, bottom, z), (w, bottom, z), (w, top, z), (-w, top, z)]
        rings.append(section)
    prop.shell(rings, surface, planar_sides=True)


def rounds(prop, surface, y, rows, sides=(24, 14, 8, 6)):
    prop.tube((0, y, 0), Z, [(z, radius) for z, radius, last in rows if prop.level <= last],
              sides[prop.level], surface)


def guard(prop, surface, outline):
    corners = [(y, z) for y, z, last in outline if prop.level <= last]
    mid_y = sum(y for y, _ in corners) / len(corners)
    mid_z = sum(z for _, z in corners) / len(corners)
    half_width = 0.012
    rings = []
    for y, z in corners:
        inner_y = mid_y + (y - mid_y) * 0.68
        inner_z = mid_z + (z - mid_z) * 0.68
        rings.append([
            (-half_width, inner_y, inner_z), (half_width, inner_y, inner_z),
            (half_width, y, z), (-half_width, y, z),
        ])
    prop.shell(rings, surface, closed=True, planar_sides=True)


