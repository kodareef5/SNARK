from math import cos, pi, sin

from hand_geometry import X, Y, Z, rounded_outline


def _outline(width, depth, clip):
    if clip:
        return rounded_outline(width, depth, clip)
    x, z = width / 2, depth / 2
    return [(-x, z), (x, z), (x, -z), (-x, -z)]


def _block(prop, low, high, surface, bevel=0):
    x0, y0, z0 = low
    x1, y1, z1 = high
    height = y1 - y0
    bevel = min(bevel, (x1 - x0) * .45, (z1 - z0) * .45) if prop.level < 2 else 0
    outline = _outline(x1 - x0, z1 - z0, bevel)
    if bevel and prop.level == 0:
        edge = min(bevel, height / 4)
        sections = ((0, .94), (edge, 1), (height - edge, 1), (height, .94))
    else:
        sections = ((0, 1), (height, 1))
    prop.panel(((x0 + x1) / 2, y0, (z0 + z1) / 2), outline, sections, surface)


def _panels(prop, center, sections, surface, clip, bands=None):
    x, z = center
    rings = [[(x + a, y, z + b) for a, b in _outline(width, depth, clip)]
             for y, width, depth in sections]
    prop.shell(rings, surface, planar_sides=True, band_surfaces=bands)


