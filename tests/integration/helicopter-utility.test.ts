import { expect, test } from "bun:test";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { ClientSession } from "../../client/core/session.ts";
import { NO_CLIPS } from "../../shared/anim/clip.ts";
import { makeHandle } from "../../shared/ids.ts";
import type { BitWriter } from "../../shared/net/codec.ts";
import { BOX_OPEN, BOX_SELF, CMD_CRAFT, CMD_CRAFT_AT, CMD_LEARN, CMD_MOVE, CMD_STRUCT, CMD_VEHICLE, RESULT_DENIED, RESULT_INVALID, RESULT_OK, RESULT_SHORT, VEHICLE_DEPLOY, VEHICLE_INSPECT, VEHICLE_REFUEL, VEHICLE_REPAIR } from "../../shared/net/protocol.ts";
import { BTN_USE } from "../../shared/sim/character.ts";
import { V_HEALTH } from "../../shared/sim/vitals.ts";
import { writeMap } from "../../shared/world/mapfile.ts";
import { NO_PIN, STRUCT_USE } from "../../shared/world/upkeep.ts";
import { VEHICLE_ORIGIN } from "../../server/vehicle-service.ts";
import { Harness } from "../fixtures/net.ts";
import { flatMap } from "../fixtures/map.ts";

/** Every inventory and deployment transition is a real command; materials and experience are fixture setup only. */
test("a learned expensive assembly crafts at a fueled fabricator, deploys, services, salvages cargo and persists without respawning found aircraft", () => {
  const dir = mkdtempSync(join(tmpdir(), "snark-heli-utility-")), dbPath = join(dir, "world.db");
  const map = writeMap(flatMap(2, { vehicles: [{ kind: "core:helicopter_police", id: "audit-yard", x: 42, z: 42, yaw: 0, condition: [.3, .8], fuel: [.1, .4] }] }));
  const options = { dev: true, clips: NO_CLIPS, rigs: [], map, dbPath };
  let h: Harness | null = null;
  try {
    h = new Harness({}, 1, 60, options);
    let s = h.join("assembler"); h.run(400);
    const send = (session: ClientSession, command: number, write: (w: BitWriter) => void): number => {
      let code = -1; session.onResult = (_, result) => { code = result; };
      session.command(command, write); h!.run(150); return code;
    };
    const id = (name: string) => h!.reg.index.get(`core:${name}`)!;
    const move = (from: number, slot: number, to: number, target: number, item: number, n = 0) => send(s, CMD_MOVE, w => { w.bits(from, 1); w.varint(slot); w.bits(to, 1); w.varint(target); w.u16(n); w.u16(item); });
    let c = h.client(s)!, actor = h.host.records.byPid.get(c.pid)!;
    const kit = id("helicopter_assembly"), gas = id("gasoline"), cargo = id("stone"), ingot = id("ingot"), kind = id("fabricator");
    const found = [...h.host.records.byPid.values()].find(r => r.kind === id("helicopter_police"))!, foundPid = found.pid;
    const foundEnt = h.host.records.entOf.get(foundPid)!, foundFuel = h.world.ents.fuel[h.world.ents.vrow[foundEnt]!]!, foundEngine = h.world.ents.vehicleEngineCondition[h.world.ents.vrow[foundEnt]!]!;
    const foundOrigin = new TextDecoder().decode(found.extra.get(VEHICLE_ORIGIN));
    h.world.ents.setPosition(c.ent, 58.8, 0, 64);
    const ref = h.world.structs.add(kind, 60, h.reg.halfY[kind]!, 64, 0, actor.team, h.reg.maxHp[kind]!), station = h.host.fixtures.ensure(ref);
    expect(send(s, CMD_STRUCT, w => { w.u32(ref); w.u8(STRUCT_USE); w.u16(NO_PIN); })).toBe(RESULT_OK);
    expect(send(s, CMD_CRAFT_AT, w => { w.u16(kit); w.u8(1); })).toBe(RESULT_DENIED);
    h.host.progression.addXp(actor, 1_000_000);
    expect(send(s, CMD_LEARN, w => w.u16(id("engram-helicopter_assembly")))).toBe(RESULT_OK);
    expect(send(s, CMD_CRAFT, w => { w.u16(kit); w.u8(1); })).toBe(RESULT_DENIED);
    const costs = [["ingot", 1600], ["polymer", 300], ["electronics", 250], ["crystal", 200], ["paste", 300]] as const;
    for (const [name, n] of costs) expect(h.host.items.mint(station, id(name), n)).toBe(n);
    expect(send(s, CMD_CRAFT_AT, w => { w.u16(kit); w.u8(1); })).toBe(RESULT_SHORT);
    h.host.items.mint(station, gas, 1); expect(h.host.stations.toggle(ref)).toBe(RESULT_OK);
    const beforeXp = actor.xp;
    expect(send(s, CMD_CRAFT_AT, w => { w.u16(kit); w.u8(1); })).toBe(RESULT_OK);
    expect(costs.map(([name]) => h!.host.items.inv(station).total(id(name)))).toEqual([0, 0, 0, 0, 0]);
    h.run(179000); expect(h.host.items.inv(station).total(kit)).toBe(0);
    h.run(1200); expect(h.host.items.inv(station).total(kit)).toBe(1); expect(actor.xp - beforeXp).toBeGreaterThanOrEqual(1200);
    const slot = s.inventory!.free();
    expect(move(BOX_OPEN, s.open!.inventory.item.indexOf(kit), BOX_SELF, slot, kit, 1)).toBe(RESULT_OK);
    expect(send(s, CMD_VEHICLE, w => { w.u8(VEHICLE_DEPLOY); w.u8(slot); w.f32(68); w.f32(0); w.f32(64); w.u16(0); })).toBe(RESULT_OK);
    const aircraft = [...h.host.records.byPid.values()].find(r => r.kind === id("helicopter"))!;
    const e = h.host.records.entOf.get(aircraft.pid)!, handle = makeHandle(e, h.world.ents.gen[e]!);
    expect(aircraft.team).toBe(actor.team); expect(h.world.ents.fuel[h.world.ents.vrow[e]!]).toBe(0); expect(h.host.items.inv(actor).total(kit)).toBe(0);
    h.world.ents.setPosition(c.ent, 64, 0, 64); h.world.history.untrack(c.ent); h.world.history.track(c.ent);
    for (const [name, n] of [["gasoline", 2], ["ingot", 40], ["polymer", 10], ["electronics", 8], ["stone", 13]] as const) h.host.items.mint(actor, id(name), n);
    expect(send(s, CMD_VEHICLE, w => { w.u8(VEHICLE_REFUEL); w.u32(handle); w.u8(2); })).toBe(RESULT_OK);
    expect(h.world.ents.fuel[h.world.ents.vrow[e]!]).toBe(10);
    h.host.urban.collision(e, 12, false); h.run(50);
    expect(h.host.survival.value(aircraft, V_HEALTH)).toBeLessThan(1400);
    expect(send(s, CMD_VEHICLE, w => { w.u8(VEHICLE_REPAIR); w.u32(handle); })).toBe(RESULT_OK);
    expect(h.host.survival.value(aircraft, V_HEALTH)).toBe(1400); expect(h.world.ents.vehicleEngineCondition[h.world.ents.vrow[e]!]).toBe(1);
    expect(send(s, CMD_VEHICLE, w => { w.u8(VEHICLE_INSPECT); w.u32(handle); })).toBe(RESULT_OK);
    expect(move(BOX_SELF, s.inventory!.item.indexOf(cargo), BOX_OPEN, s.open!.inventory.free(), cargo, 13)).toBe(RESULT_OK);
    expect(h.host.items.inv(aircraft).total(cargo)).toBe(13);
    h.host.survival.hurt(aircraft, 1e6, 0); h.run(100);
    const wreck = [...h.host.corpses.bodies.values()].find(b => b.kind === id("helicopter"))!, wreckPid = wreck.rec.pid;
    expect(h.host.items.inv(wreck.rec).total(cargo)).toBe(13); expect(h.host.items.audit()).toEqual([]);
    const wreckHandle = makeHandle(wreck.e, h.world.ents.gen[wreck.e]!);
    expect(send(s, CMD_VEHICLE, w => { w.u8(VEHICLE_INSPECT); w.u32(wreckHandle); })).toBe(RESULT_OK);
    expect(s.log.at(-1)!.text).toContain("salvage wreck"); expect(c.open).toBe(wreckPid);
    h.host.items.mint(actor, gas, 1);
    expect(send(s, CMD_VEHICLE, w => { w.u8(VEHICLE_REFUEL); w.u32(wreckHandle); w.u8(1); })).toBe(RESULT_INVALID);
    expect(send(s, CMD_VEHICLE, w => { w.u8(VEHICLE_REPAIR); w.u32(wreckHandle); })).toBe(RESULT_INVALID);
    expect(h.host.items.inv(actor).total(gas)).toBe(1);
    h.host.shutdown(); h = new Harness({}, 1, 60, options); s = h.join("assembler"); h.run(400);
    c = h.client(s)!; actor = h.host.records.byPid.get(c.pid)!;
    const savedWreck = h.host.corpses.bodies.get(wreckPid)!;
    expect(savedWreck).toBeDefined(); expect(h.host.items.inv(savedWreck.rec).total(cargo)).toBe(13);
    const savedFound = h.host.records.byPid.get(foundPid)!, savedFoundEnt = h.host.records.entOf.get(foundPid)!;
    expect(new TextDecoder().decode(savedFound.extra.get(VEHICLE_ORIGIN))).toBe(foundOrigin);
    expect([h.world.ents.fuel[h.world.ents.vrow[savedFoundEnt]!], h.world.ents.vehicleEngineCondition[h.world.ents.vrow[savedFoundEnt]!]]).toEqual([foundFuel, foundEngine]);
    expect([...h.host.records.byPid.values()].filter(r => r.kind === id("helicopter_police"))).toHaveLength(1);
    expect([...h.host.records.byPid.values()].filter(r => r.kind === id("helicopter"))).toHaveLength(0);
    expect(h.host.items.inv(actor).total(kit)).toBe(0);
    // The ordinary use ray opens salvage; cargo comes back through the ordinary two-inventory move.
    h.world.ents.setPosition(c.ent, savedWreck.x - 4, savedWreck.y, savedWreck.z);
    h.pilots[0]!.yaw = Math.PI / 2; h.pilots[0]!.buttons = BTN_USE; h.run(150); h.pilots[0]!.buttons = 0; h.run(100);
    expect(c.open).toBe(wreckPid);
    expect(move(BOX_OPEN, s.open!.inventory.item.indexOf(cargo), BOX_SELF, s.inventory!.free(), cargo, 13)).toBe(RESULT_OK);
    const beforeMetal = h.host.items.inv(actor).total(ingot);
    expect(h.host.corpses.struck(actor, savedWreck.e, 600, id("pick"))).toBe(true);
    expect(h.host.corpses.bodies.has(wreckPid)).toBe(false);
    expect(h.host.items.inv(actor).total(ingot)).toBeGreaterThan(beforeMetal); expect(h.host.items.audit()).toEqual([]);
    h.host.shutdown(); h = new Harness({}, 1, 60, options); s = h.join("assembler"); h.run(400);
    actor = h.host.records.byPid.get(h.client(s)!.pid)!;
    expect(h.host.items.inv(actor).total(cargo)).toBe(13); expect(h.host.items.inv(actor).total(kit)).toBe(0);
    expect(h.host.corpses.bodies.has(wreckPid)).toBe(false);
    expect([...h.host.records.byPid.values()].filter(r => r.kind === id("helicopter_police"))).toHaveLength(1);
    expect(h.host.items.audit()).toEqual([]);
  } finally { h?.host.shutdown(); rmSync(dir, { recursive: true, force: true }); }
});
