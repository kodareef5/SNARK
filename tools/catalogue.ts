// Writes planning/reference/catalogue.md from the class table (bun run catalogue). The page is derived, never edited.
// A test fails if the page is not what this tool writes.

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { CORE_CONTENT } from "../content/core.ts";
import { CLASSES, FIELDS, classOf, type ClassRow, type Field, type Slot } from "../shared/content/classes.ts";
import { FEATURES, type Feature } from "../shared/features.ts";

export const CATALOGUE_PAGE = resolve(import.meta.dir, "../planning/reference/catalogue.md");

const FAMILIES: readonly [type: string, title: string][] = [
  ["item", "Items"],
  ["engram", "Engrams"],
  ["levels", "Levels"],
  ["species", "Species"],
  ["structure", "Structures"],
  ["shape", "Shapes"],
  ["material", "Materials"],
  ["node", "Nodes"],
  ["prop", "Props"],
  ["buff", "Buffs"],
  ["damage", "Damage types"],
  ["loot", "Loot"],
  ["spawns", "Spawns"],
  ["map", "Maps"],
  ["game", "The game"],
  ["population", "Populations"],
  ["rename", "Renames"],
];

const cell = (text: string): string => text.replaceAll("|", "\\|");
const code = (names: readonly string[]): string => (names.length === 0 ? "" : names.map((n) => `\`${n}\``).join(", "));

function standing(r: ClassRow): string {
  if (r.abstract) return "a group";
  return r.waits === "" ? r.status : `${r.status}: ${r.waits}`;
}

function slotLine(name: string, s: Slot): string {
  const keys = s.keys === undefined ? "" : typeof s.keys === "string" ? `/<${s.keys}>` : `/{${s.keys.join(", ")}}`;
  return `\`#${name}${keys}\` ${s.asset}, ${s.need}${s.when ? ` with \`${s.when}\`` : ""}, from \`${s.from}\`, else ${s.fallback.map((f) => `\`${f}\``).join(" then ")}`;
}

/** The core pack's ids by class, as the content stands. */
function coreByClass(): Map<string, string[]> {
  const out = new Map<string, string[]>();
  for (const d of CORE_CONTENT) {
    const c = classOf(d);
    const list = out.get(c) ?? [];
    list.push(d.id);
    out.set(c, list);
  }
  return out;
}

export function cataloguePage(): string {
  const core = coreByClass();
  const leaves = CLASSES.filter((r) => !r.abstract);
  const count = (status: string): number => leaves.filter((r) => r.status === status).length;
  const out: string[] = [];
  out.push("# Content catalogue", "");
  out.push("Generated by `bun run catalogue` from the class table in");
  out.push("`shared/content/classes.ts`. Do not edit it by hand: change the table and run");
  out.push("the tool.", "");
  out.push("Every kind of content has a class, as ARK's has. A definition's `type` is its");
  out.push("family and its class is a leaf of this table. The table says what a class must");
  out.push("declare, what it may, and which assets it expects. A field that is in neither");
  out.push("list is refused. Names and ids are this engine's own. The ARK column says what");
  out.push("the class corresponds to, so that what is known of ARK carries over.", "");
  out.push(`There are ${leaves.length} classes: ${count("built")} built, ${count("partial")} partly built, and ${count("stub")} stubs that`);
  out.push(`wait for a feature. The core pack holds ${CORE_CONTENT.length} definitions.`, "");
  out.push("An asset slot is addressed `owner#slot`, or `owner#slot/key` for a slot with");
  out.push("several values: `core:raptor#clip/walk`. Levels of detail are inside the asset");
  out.push("and are never named by content.", "");
  out.push("A definition is named by its id. At the console and in a settings file it also");
  out.push("answers to an id it once had, to an alias (`aliases`, which any definition may");
  out.push("declare and no two may share), and to its id's own name where it alone answers");
  out.push("to that: `spear` for `core:spear`. Case is ignored. A creature and its variants");
  out.push("share a `tag`.", "");

  for (const [type, title] of FAMILIES) {
    const here = CLASSES.filter((r) => r.type === type);
    if (here.length === 0) continue;
    out.push(`## ${title}`, "");
    out.push("| Class | ARK | Standing | Must | May | In core |", "| --- | --- | --- | --- | --- | --- |");
    for (const r of here) {
      const must = r.any.length > 0 ? [code(r.must), `one of ${code(r.any)}`].filter((x) => x !== "").join("; ") : code(r.must);
      out.push(`| \`${r.id}\` | ${cell(r.ark)} | ${standing(r)} | ${must} | ${code(r.may)} | ${r.abstract ? "" : (core.get(r.id)?.length ?? 0)} |`);
    }
    out.push("");
    for (const r of here) out.push(`- **\`${r.id}\`** on shelf \`${r.shelf}\`. ${r.doc}`);
    out.push("");
    const slotted = here.filter((r) => Object.keys(r.slots).length > 0);
    if (slotted.length > 0) {
      out.push("Asset slots:", "");
      for (const r of slotted) out.push(`- \`${r.id}\`: ${Object.entries(r.slots).map(([name, s]) => slotLine(name, s)).join("; ")}.`);
      out.push("");
    }
    const fields: Record<string, Field> | undefined = (FIELDS as Record<string, Record<string, Field>>)[type];
    if (fields) {
      const arks = Object.entries(fields).filter(([, f]) => f.ark !== "");
      if (arks.length > 0) out.push(`ARK's names: ${arks.map(([name, f]) => `\`${name}\` is ${cell(f.ark)}`).join("; ")}.`, "");
      const refs = Object.entries(fields).flatMap(([name, f]) => Object.entries(f.refs ?? {}).map(([path, to]) => `\`${name}${path === "" ? "" : path.startsWith("[") ? path : `.${path}`}\` names a \`${to}\``));
      if (refs.length > 0) out.push(`What names what: ${refs.join("; ")}.`, "");
      const open = Object.entries(fields).filter(([, f]) => f.open).map(([name]) => name);
      if (open.length > 0) out.push(`Packs may add to: ${code(open)}.`, "");
    }
  }

  out.push("## What waits for a feature", "");
  out.push("Each class below has a row and no content, and each field is declared and");
  out.push("checked and read by nothing. They are filled in when the feature under them is");
  out.push("built.", "");
  for (const feature of Object.keys(FEATURES) as Feature[]) {
    const waiting = leaves.filter((r) => r.waits === feature).map((r) => `\`${r.id}\`${r.status === "partial" ? " (partly built)" : ""}`);
    for (const [type, fields] of Object.entries(FIELDS)) {
      for (const [name, f] of Object.entries(fields) as [string, Field][]) {
        if (f.waits === feature) waiting.push(`\`${type}.${name}\``);
        for (const [part, waits] of Object.entries(f.stubs ?? {})) if (waits === feature) waiting.push(`\`${type}.${name}.${part}\``);
      }
    }
    if (waiting.length === 0) continue;
    out.push(`- **${FEATURES[feature]}.** ${waiting.join(", ")}.`);
  }
  out.push("");

  out.push("## The core pack by class", "");
  for (const r of leaves) {
    const ids = core.get(r.id);
    if (!ids) continue;
    out.push(`**\`${r.id}\`** (${ids.length}): ${ids.map((id) => id.replace(/^core:/, "")).join(", ")}.`, "");
  }
  return out.join("\n");
}

if (import.meta.main) {
  writeFileSync(CATALOGUE_PAGE, cataloguePage());
  console.log(`${CATALOGUE_PAGE}\n${CLASSES.filter((r) => !r.abstract).length} classes, ${CORE_CONTENT.length} definitions`);
}
