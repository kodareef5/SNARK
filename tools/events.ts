// Writes planning/reference/events.md from the event table (bun run events). The page is derived, never edited.
// A test fails if the page is not what this tool writes.

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { EVENTS, type EventRow } from "../server/events/catalog.ts";
import { FEATURES, type Feature } from "../shared/features.ts";

export const EVENTS_PAGE = resolve(import.meta.dir, "../planning/reference/events.md");

const GROUPS: Readonly<Record<string, string>> = {
  server: "The server",
  command: "Commands",
  session: "Sessions",
  zone: "Zones",
  chat: "Chat",
  name: "Names",
  damage: "Combat",
  damaged: "Combat",
  death: "Combat",
  body: "Combat",
  projectile: "Combat",
  xp: "Progression",
  level: "Progression",
  stat: "Progression",
  engram: "Progression",
  creature: "Creatures",
  tame: "Creatures",
  ride: "Creatures",
  breed: "Creatures",
  imprint: "Creatures",
  carry: "Creatures",
  build: "Structures",
  structure: "Structures",
  item: "Items",
  container: "Items",
  craft: "Items",
  harvest: "Items",
  tribe: "Tribes",
  transfer: "The cluster",
  cluster: "The cluster",
  perm: "Services",
  ban: "Services",
  points: "Services",
  limit: "Services",
  protect: "Services",
  module: "Modules",
  mapevent: "Map events",
};

export const groupOf = (r: EventRow): string => GROUPS[r.name.split(".")[0]!] ?? "";
const cell = (text: string): string => text.replaceAll("|", "\\|");
const standing = (r: EventRow): string => (r.status === "planned" ? `planned: ${r.waits}` : r.status);

export function eventsPage(): string {
  const count = (status: string): number => EVENTS.filter((r) => r.status === status).length;
  const out: string[] = [];
  out.push("# Events", "");
  out.push("Generated by `bun run events` from the event table in");
  out.push("`server/events/catalog.ts`. Do not edit it by hand: change the table and run the");
  out.push("tool.", "");
  out.push("An event is what the server tells a module. A **before** event is raised before");
  out.push("the thing happens: a handler may refuse it with a reason, or change the fields");
  out.push("marked \"may change\". An **after** event says what has happened, in values, and");
  out.push("is delivered once a tick, before the commit. The module contract is in");
  out.push("`server/api/module.ts`.", "");
  out.push(`There are ${EVENTS.length} events: ${count("wired")} raised today, ${count("stub")} with a place in the code and not`);
  out.push(`raised yet, and ${count("planned")} that wait for a feature.`, "");
  out.push("The ARK column says what a plugin for ARK's unofficial server API hooks for the");
  out.push("same purpose. ARK has no event API, so plugins hook the game's own functions.", "");

  const titles = [...new Set(EVENTS.map(groupOf))];
  for (const title of titles) {
    out.push(`## ${title}`, "");
    out.push("| Event | Phase | Tells | May change | ARK | Raised in | Standing |", "| --- | --- | --- | --- | --- | --- | --- |");
    for (const r of EVENTS.filter((e) => groupOf(e) === title)) {
      out.push(`| \`${r.name}\`${r.hot ? " (hot)" : ""} | ${r.phase} | ${r.fields.map((f) => `\`${f}\``).join(", ")} | ${r.changes.map((f) => `\`${f}\``).join(", ")} | ${cell(r.ark)} | \`${r.at}\` | ${standing(r)} |`);
    }
    out.push("");
    for (const r of EVENTS.filter((e) => groupOf(e) === title)) out.push(`- **\`${r.name}\`.** ${r.doc}`);
    out.push("");
  }

  out.push("## What waits for a feature", "");
  for (const feature of Object.keys(FEATURES) as Feature[]) {
    const waiting = EVENTS.filter((r) => r.waits === feature);
    if (waiting.length > 0) out.push(`- **${FEATURES[feature]}.** ${waiting.map((r) => `\`${r.name}\``).join(", ")}.`);
  }
  out.push("");
  return out.join("\n");
}

if (import.meta.main) {
  writeFileSync(EVENTS_PAGE, eventsPage());
  console.log(`${EVENTS_PAGE}\n${EVENTS.length} events`);
}
