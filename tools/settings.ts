// Writes planning/reference/settings.md from the catalogue (bun run settings). The page is derived, never edited.
// A test fails if the page is not what this tool writes.

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { CATALOG, catalogCounts } from "../server/settings/catalog.ts";
import { FEATURES, NOT_HERE, type Feature, type NotHere, type Place, type Row } from "../server/settings/row.ts";

export const SETTINGS_PAGE = resolve(import.meta.dir, "../planning/reference/settings.md");

const PLACES: Record<Place, string> = {
  server: "GameUserSettings.ini `[ServerSettings]`",
  session: "GameUserSettings.ini `[SessionSettings]`",
  motd: "GameUserSettings.ini `[MessageOfTheDay]`",
  gamesession: "GameUserSettings.ini `[/Script/Engine.GameSession]`",
  map: "GameUserSettings.ini, a map's own section",
  snark: "GameUserSettings.ini `[SnarkSettings]`",
  mode: "Game.ini `[/script/shootergame.shootergamemode]`",
  cli: "Command line",
  dynamic: "The live file",
};

function shown(row: Row): string {
  if (row.kind === "struct" || row.kind === "names" || row.kind === "lines") return "none";
  if (row.kind === "indexed") {
    // One number for all, then the indexes that differ from it.
    const d = row.def as readonly number[];
    const most = d.filter((v) => v === d[1]).length >= d.length / 2 ? d[1]! : d[0]!;
    const odd = d.flatMap((v, n) => (v === most ? [] : [`[${n}] ${v}`]));
    return odd.length === 0 ? `${most} each` : `${most} each; ${odd.join(", ")}`;
  }
  if (row.kind === "flag") return row.def === false ? "not given" : "none";
  if (row.kind === "bool") return row.def ? "True" : "False";
  if (row.kind === "text") return row.def === "" ? "none" : `\`${String(row.def)}\``;
  return String(row.def);
}

const written = (row: Row): string => (row.kind === "flag" ? `-${row.name}${row.def === false ? "" : "="}` : row.kind === "indexed" ? `${row.name}[n]` : row.name);
const cell = (text: string): string => text.replaceAll("|", "\\|");

function table(rows: readonly Row[], extra: (r: Row) => string, head: string): string[] {
  const out = [`| Setting | Default | What it does | ${head} |`, "| --- | --- | --- | --- |"];
  for (const r of rows) out.push(`| \`${written(r)}\` | ${shown(r)} | ${cell(r.doc)}${r.note ? ` *${cell(r.note)}*` : ""} | ${extra(r)} |`);
  return out;
}

/** Rows in the order of the catalogue, under each place in turn. */
function byPlace(rows: readonly Row[], each: (place: Place, rows: Row[]) => void): void {
  for (const place of Object.keys(PLACES) as Place[]) {
    const here = rows.filter((r) => r.at === place);
    if (here.length > 0) each(place, here);
  }
}

export function settingsPage(): string {
  const n = catalogCounts();
  const out: string[] = [];
  out.push("# Server settings", "");
  out.push("Generated by `bun run settings` from the catalogue in `server/settings`. Do not");
  out.push("edit it by hand: change the catalogue and run the tool.", "");
  out.push("A server is configured as ARK's is ([how](round5-settings.md), and [what the");
  out.push("values mean](round5-game-ini.md)). Every setting an ARK dedicated server reads");
  out.push(`is listed here, ${n.all} of them: ${n.live} take effect,${n.todo > 0 ? ` ${n.todo} more will by the end of the round being built,` : ""}`);
  out.push(`${n.planned} wait for a feature that is not built yet, and ${n.none} have no meaning in this`);
  out.push("engine. A setting that does not take effect is still read, checked and");
  out.push("reported when the server starts.", "");
  out.push("Names are matched without regard to case. Lists that name classes take this");
  out.push("engine's content ids. \"While running\" says whether the console or the live file");
  out.push("may change a setting without a restart.", "");

  const live = CATALOG.filter((r) => r.status === "live");
  out.push("## What takes effect", "");
  byPlace(live, (place, rows) => {
    out.push(`### ${PLACES[place]}`, "");
    out.push(...table(rows, (r) => `${r.live ? "yes" : "no"}${r.client ? "; clients are told" : ""}`, "While running"), "");
  });

  const todo = CATALOG.filter((r) => r.status === "todo");
  if (todo.length > 0) {
    out.push("## What will take effect this round", "");
    byPlace(todo, (place, rows) => {
      out.push(`### ${PLACES[place]}`, "");
      out.push(...table(rows, (r) => r.waits, "From"), "");
    });
  }

  out.push("## What waits for a feature", "");
  out.push("Each heading is something this engine does not do yet, and under it the");
  out.push("settings that will take effect when it does. This is the list that guides");
  out.push("what is built next.", "");
  for (const feature of Object.keys(FEATURES) as Feature[]) {
    const rows = CATALOG.filter((r) => r.status === "planned" && r.waits === feature);
    if (rows.length === 0) continue;
    out.push(`### ${FEATURES[feature]}`, "");
    out.push(...table(rows, (r) => PLACES[r.at].replace(/ `.*$/, ""), "Where"), "");
  }

  out.push("## What has no meaning here", "");
  for (const why of Object.keys(NOT_HERE) as NotHere[]) {
    const rows = CATALOG.filter((r) => r.status === "none" && r.waits === why);
    if (rows.length === 0) continue;
    out.push(`**${NOT_HERE[why]}.** ${rows.map((r) => `\`${written(r)}\``).join(", ")}.`, "");
  }
  return out.join("\n");
}

if (import.meta.main) {
  writeFileSync(SETTINGS_PAGE, settingsPage());
  const n = catalogCounts();
  console.log(`${SETTINGS_PAGE}\n${n.all} settings: ${n.live} live, ${n.todo} to come this round, ${n.planned} planned, ${n.none} not applicable`);
}
